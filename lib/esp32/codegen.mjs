import {ESP32_CLASSIC_REFERENCE} from './pins.mjs';
import {getEsp32BoardProfile} from './board-profiles.mjs';

const BOARD_PROFILES = {
  'esp32:esp32:esp32': ESP32_CLASSIC_REFERENCE,
  'esp32:esp32:esp32s3': getEsp32BoardProfile('esp32-s3-devkitc-1-v1.1'),
  'esp32:esp32:esp32c3': getEsp32BoardProfile('esp32-c3-devkitm-1')
};

export function getEsp32CodegenProfile(board) {
  return BOARD_PROFILES[board] || null;
}

export function getEsp32CodegenOptions(board, experiment='led-blink') {
  const profile=getEsp32CodegenProfile(board);
  if(!profile)return [];
  return profile.pins.filter(pin => {
    if(experiment==='analog-read')return pin.capabilities.includes('ADC')||pin.capabilities.includes('ADC1');
    if(experiment==='button-input')return pin.capabilities.includes('Digital I/O');
    return pin.capabilities.includes('Digital I/O') && !pin.capabilities.includes('Digital input');
  });
}

export function generateEsp32Sketch({board,experiment='led-blink',gpio}) {
  const profile=getEsp32CodegenProfile(board);
  const pin=profile?.pins.find(item=>item.gpio===Number(gpio));
  if(!profile||!pin)throw new Error('Choose a GPIO from a supported physical-board reference.');
  const valid=getEsp32CodegenOptions(board,experiment).some(item=>item.gpio===pin.gpio);
  if(!valid)throw new Error('The selected GPIO does not support this experiment.');
  const caveats=pin.restrictions.length?pin.restrictions.map(item=>'// PIN CAUTION: '+item).join('\n')+'\n':'';
  const header='// Generated by CircuitByte Studio for '+profile.name+'\n// Verify your exact module, board revision, header labels and wiring before powering.\n// ESP32 GPIO is 3.3V logic and is not 5V tolerant.\n'+caveats+'\n';
  if(experiment==='led-blink')return header+'constexpr uint8_t LED_GPIO = '+pin.gpio+';\n\nvoid setup() {\n  pinMode(LED_GPIO, OUTPUT);\n}\n\nvoid loop() {\n  digitalWrite(LED_GPIO, HIGH);\n  delay(500);\n  digitalWrite(LED_GPIO, LOW);\n  delay(500);\n}\n';
  if(experiment==='button-input')return header+'constexpr uint8_t BUTTON_GPIO = '+pin.gpio+';\n\nvoid setup() {\n  pinMode(BUTTON_GPIO, INPUT_PULLUP);\n  Serial.begin(115200);\n}\n\nvoid loop() {\n  static int previous = HIGH;\n  const int current = digitalRead(BUTTON_GPIO);\n  if (current != previous) {\n    Serial.println(current == LOW ? "Pressed" : "Released");\n    previous = current;\n  }\n  delay(20); // Polling example; add application-specific debounce.\n}\n';
  if(experiment==='analog-read')return header+'constexpr uint8_t SENSOR_GPIO = '+pin.gpio+';\n\nvoid setup() {\n  Serial.begin(115200);\n}\n\nvoid loop() {\n  const int reading = analogRead(SENSOR_GPIO);\n  Serial.println(reading);\n  delay(250);\n}\n';
  throw new Error('Unsupported ESP32 code-generation experiment.');
}
